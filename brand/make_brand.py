"""Build the SOOTH brand kit as self-contained SVGs (all text outlined, no font needed to view them).

Run:  python brand/make_brand.py        (needs fontTools; fonts in brand/fonts are OFL, from Google Fonts)
PNGs for X are rendered from these SVGs separately (see brand/README.md).
"""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

HERE = Path(__file__).parent
CANVAS, LINE, INK, MUTED, GREEN = "#E9E9E7", "#B9B9B4", "#111111", "#6B6B66", "#7FFAB7"

# Aperture mark, radius 60 around (0, 0) — generated by the 26 Oct logo script.
APERTURE = [
    "M19.32 -6.54 L57.90 15.74 A60.0 60.0 0 0 1 19.32 56.80 Z",
    "M15.32 13.46 L15.32 58.01 A60.0 60.0 0 0 1 -39.53 45.13 Z",
    "M-4.00 20.00 L-42.58 42.27 A60.0 60.0 0 0 1 -58.85 -11.67 Z",
    "M-19.32 6.54 L-57.90 -15.74 A60.0 60.0 0 0 1 -19.32 -56.80 Z",
    "M-15.32 -13.46 L-15.32 -58.01 A60.0 60.0 0 0 1 39.53 -45.13 Z",
    "M4.00 -20.00 L42.58 -42.27 A60.0 60.0 0 0 1 58.85 11.67 Z",
]
MARK_RADIUS = 60


class Font:
    def __init__(self, filename: str):
        self.tt = TTFont(HERE / "fonts" / filename)
        self.glyphs = self.tt.getGlyphSet()
        self.cmap = self.tt.getBestCmap()
        self.upm = self.tt["head"].unitsPerEm

    def _names(self, text: str) -> list[str]:
        missing = [ch for ch in text if ord(ch) not in self.cmap]
        if missing:
            raise ValueError(f"glyphs missing from font: {missing}")
        return [self.cmap[ord(ch)] for ch in text]

    def width(self, text: str, size: float, tracking: float = 0.0) -> float:
        names = self._names(text)
        advance = sum(self.tt["hmtx"][n][0] for n in names) * size / self.upm
        return advance + tracking * size * (len(names) - 1)

    def path(self, text: str, size: float, x: float, baseline: float, tracking: float = 0.0, fill: str = INK) -> str:
        """Outlined text as one <path>. x is the left edge, tracking is in em."""
        scale = size / self.upm
        pen = SVGPathPen(self.glyphs, ntos=lambda v: f"{v:.1f}")
        cursor = x
        for name in self._names(text):
            self.glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, cursor, baseline)))
            cursor += self.tt["hmtx"][name][0] * scale + tracking * size
        return f'<path fill="{fill}" d="{pen.getCommands()}"/>'

    def centered(self, text: str, size: float, cx: float, baseline: float, tracking: float = 0.0, fill: str = INK) -> str:
        return self.path(text, size, cx - self.width(text, size, tracking) / 2, baseline, tracking, fill)


TEKTUR = Font("Tektur.ttf")
INTER = Font("InterTight.ttf")
MONO = Font("JetBrainsMono.ttf")


def mark(cx: float, cy: float, radius: float, fill: str = INK) -> str:
    blades = "".join(f'<path d="{d}"/>' for d in APERTURE)
    return f'<g transform="translate({cx} {cy}) scale({radius / MARK_RADIUS:.4f})" fill="{fill}">{blades}</g>'


def svg(width: int, height: int, body: str, title: str) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img"><title>{title}</title>{body}</svg>\n'
    )


def write(name: str, content: str) -> None:
    (HERE / name).write_text(content, encoding="utf-8")
    print(f"wrote brand/{name}")


def wordmark_svg() -> str:
    size, pad = 120, 8
    w = TEKTUR.width("sooth", size, -0.03)
    return svg(round(w + 2 * pad), 120, TEKTUR.path("sooth", size, pad, 92, -0.03), "sooth wordmark")


def lockup_svg() -> str:
    size, r, gap = 64, 30, 18
    w = TEKTUR.width("sooth", size, -0.03)
    body = mark(r + 2, 40, r) + TEKTUR.path("sooth", size, 2 * r + gap + 2, 62, -0.03)
    return svg(round(2 * r + gap + w + 6), 80, body, "sooth logo lockup")


def banner_svg(width: int, height: int, title: str) -> str:
    """X banner (1500x500) and link-preview image (1200x630) share one layout."""
    band = 80
    third = width / 4
    card_w, card_h = max(width * 0.25, 340), height * 0.4
    card_x, card_y = width - card_w - 40, height / 2 - card_h / 2 + 10
    # The wordmark must end before the card, or the "h" disappears behind it.
    room_left, room_right = 40, card_x - 30
    word_size = min(height * 0.62, (room_right - room_left) / TEKTUR.width("sooth", 1, -0.05))
    word_base = height / 2 + word_size * 0.33
    word_cx = (room_left + room_right) / 2
    lines = [
        f'<rect width="{width}" height="{height}" fill="{CANVAS}"/>',
        f'<path stroke="{LINE}" d="M0 {band}H{width}M0 {height - band}H{width}'
        f'M{third} 0V{band}M{width - third} 0V{band}M{third} {height - band}V{height}M{width - third} {height - band}V{height}"/>',
        MONO.path("ORACLE / NEAR / 2026", 15, 24, band / 2 + 5, 0.08, MUTED),
        MONO.centered("MANY AGENTS. ONE TRUTH.", 15, width / 2, band / 2 + 5, 0.12),
        mark(width - 150, band / 2, 15),
        TEKTUR.path("sooth", 26, width - 126, band / 2 + 9, -0.03),
        TEKTUR.centered("sooth", word_size, word_cx, word_base, -0.05),
        f'<rect x="{card_x}" y="{card_y}" width="{card_w}" height="{card_h}" fill="{GREEN}"/>',
        MONO.path("LIVE · AGENTS STAKE", 13, card_x + 18, card_y + 32, 0.08),
        INTER.path("AI agents stake on", 25, card_x + 18, card_y + card_h * 0.52, -0.03),
        INTER.path("the truth. Liars", 25, card_x + 18, card_y + card_h * 0.52 + 30, -0.03),
        INTER.path("get slashed.", 25, card_x + 18, card_y + card_h * 0.52 + 60, -0.03),
        MONO.path("BUILT ON NEAR", 13, width - third + 24, height - band / 2 + 5, 0.08, MUTED),
    ]
    return svg(width, height, "".join(lines), title)


def main() -> None:
    for name, fill in (("mark-ink.svg", INK), ("mark-green.svg", GREEN)):
        write(name, svg(150, 150, mark(75, 75, MARK_RADIUS, fill), "sooth mark"))
    write("favicon.svg", svg(64, 64, f'<rect width="64" height="64" rx="14" fill="{GREEN}"/>' + mark(32, 32, 24), "sooth"))
    write("apple-touch-icon.svg", svg(180, 180, f'<rect width="180" height="180" fill="{GREEN}"/>' + mark(90, 90, 62), "sooth"))
    write("wordmark.svg", wordmark_svg())
    write("lockup.svg", lockup_svg())
    write("x-avatar.svg", svg(400, 400, f'<rect width="400" height="400" fill="{GREEN}"/>' + mark(200, 200, 125), "sooth"))
    write("x-banner.svg", banner_svg(1500, 500, "sooth X banner"))
    write("og.svg", banner_svg(1200, 630, "sooth: truth, settled by agents"))


if __name__ == "__main__":
    main()
