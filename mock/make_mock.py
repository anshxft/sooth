def summary(q):
    rv = q["rounds"][-1]
    ends = {"Scheduled": rv["commit_start"], "Commit": rv["commit_end"], "Reveal": rv["reveal_end"],
            "Challenge": q["challenge_end"]}
    return {
        "id": q["id"], "text": q["text"], "category": q["category"], "status": q["status"],
        "phase": q["phase"], "round": q["round"], "fee": q["fee"], "resolve_after": q["resolve_after"],
        "phase_ends_at": ends.get(q["phase"]), "commits": len(rv["commits"]), "reveals": len(rv["reveals"]),
        "outcome": q["outcome"],
    }


def build_agents(questions):
    locked, earned, slashed = {}, {}, {}
    for q in questions:
        for p in q["payouts"]:
            delta = int(p["delta"])
            if delta > 0:
                earned[p["account_id"]] = earned.get(p["account_id"], 0) + delta
            else:
                slashed[p["account_id"]] = slashed.get(p["account_id"], 0) - delta
        if q["status"] != "Finalized":
            for rv in q["rounds"]:
                for c in rv["commits"]:
                    locked[c["account_id"]] = locked.get(c["account_id"], 0) + int(c["stake"])
    agents = []
    for name, (model, answered, correct, no_reveal, registered) in AGENTS.items():
        acc_id = account(name)
        balance = near("6") + earned.get(acc_id, 0) - slashed.get(acc_id, 0)
        assert balance >= locked.get(acc_id, 0), f"{name} cannot cover its locked stakes"
        agents.append({
            "account_id": acc_id, "name": name, "model": model, "registered_at": ns(registered),
            "free_balance": str(balance - locked.get(acc_id, 0)), "locked_balance": str(locked.get(acc_id, 0)),
            "rep_bps": rep_bps(answered, correct), "accuracy_bps": accuracy_bps(answered, correct),
            "stats": {
                "answered": answered, "correct": correct, "wrong": answered - correct, "no_reveal": no_reveal,
                "earned": str(earned.get(acc_id, 0)), "slashed": str(slashed.get(acc_id, 0)),
            },
        })
    return sorted(agents, key=lambda a: (-a["rep_bps"], -a["accuracy_bps"]))


def self_check():
    assert rep_bps(0, 0) == 5_000, "new agent starts at 0.5x"
    assert rep_bps(8, 3) == 5_000, "worse than a coin flip is floored at 0.5x"
    assert 19_990 < rep_bps(1_000_000, 1_000_000) < 20_000, "perfect record approaches 2.0x"
    assert weight(near("1"), 15_000, 88) == near("1.32")


def main():
    self_check()
    questions = build_questions()
    agents = build_agents(questions)
    now = ns(NOW)
    (OUT / "questions.json").write_text(json.dumps(
        {"_note": NOTE, "now": now, "questions": questions, "summaries": [summary(q) for q in questions]}, indent=2))
    (OUT / "agents.json").write_text(json.dumps({"_note": NOTE, "now": now, "agents": agents}, indent=2))

    def to_near(yocto) -> str:
        return f"{int(yocto) / 10**24:+.6f}"

    q40 = questions[0]
    print(f"Q40 test vector: share {q40['outcome']['share_bps']} bps, avg conf {q40['outcome']['avg_conf_bps']} bps")
    for p in q40["payouts"]:
        print(f"  {p['account_id']:<26} {p['reason']:<8} {to_near(p['delta'])} NEAR")
    print(f"  protocol fee {to_near(q40['protocol_fee'])} NEAR, dust {q40['dust']} yocto")
    t41 = questions[1]["rounds"][0]["tally"]
    print(f"Q41 round 1: {t41['winner']} at {t41['share_bps']} bps, avg conf {t41['avg_conf_bps']} -> round 2")
    print("phases:", {q["id"]: q["phase"] for q in questions})
    print("agents:", [(a["name"], a["rep_bps"]) for a in agents])
    print("all checks passed")


if __name__ == "__main__":
    main()
