"""Generate mock data that follows interface.md exactly, and check the payout math.

Run:  python mock/make_mock.py   -> writes mock/questions.json and mock/agents.json

The math below is the reference for payout.rs (interface.md section 5). The asserts are the
30 Oct "payout formula sanity check"; question 40 is the test vector for the Rust tests.
All data is fictional.
"""
import hashlib
import json
from decimal import Decimal
from pathlib import Path

OUT = Path(__file__).parent
NOW = 1_793_945_520  # 2026-11-06 06:12:00 UTC, the mock "current time" (seconds)
TIMINGS = {"commit_secs": 180, "reveal_secs": 120, "challenge_secs": 180}
PROTOCOL_FEE_BPS, AUTO_SHARE_BPS, AUTO_CONF_BPS, MIN_AGENTS = 500, 8000, 7000, 3
ASKER = "asker.soothdev.testnet"
NOTE = "Fictional mock data for UI and agent development. Generated by mock/make_mock.py."


def near(amount: str) -> int:
    return int(Decimal(amount) * 10**24)


def ns(seconds: int) -> str:
    return str(seconds * 10**9)


def sha256_hex(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


# name: (model, answered, correct, no_reveal, registered_at seconds)
AGENTS = {
    "atlas": ("gemini-2.5-flash", 10, 9, 0, NOW - 86_400 * 5),
    "nova": ("openai/gpt-oss-120b", 8, 7, 0, NOW - 86_400 * 5),
    "sage": ("qwen/qwen3.8-27b", 28, 22, 1, NOW - 86_400 * 5),
    "echo": ("openai/gpt-oss-20b", 28, 18, 2, NOW - 86_400 * 4),
    "mallory": ("bribed", 8, 3, 0, NOW - 86_400 * 3),
}


def account(name: str) -> str:
    return f"{name}.soothdev.testnet"


def accuracy_bps(answered: int, correct: int) -> int:
    return (correct + 1) * 10_000 // (answered + 2)


def rep_bps(answered: int, correct: int) -> int:
    return 5_000 + 15_000 * max(0, 2 * (correct + 1) - (answered + 2)) // (answered + 2)


def weight(stake: int, rep: int, confidence: int) -> int:
    return stake * rep * confidence // (10_000 * 100)


def commit_hash(qid: int, rnd: int, agent: str, answer: str, conf: int, evidence_hash: str, salt: str) -> str:
    return sha256_hex(f"{qid}|{rnd}|{agent}|{answer}|{conf}|{evidence_hash}|{salt}")


def make_round(qid, rnd, min_stake, commit_start, entries):
    """entries: (name, stake, answer, confidence, revealed). answer/confidence stay hidden until revealed."""
    commit_end = commit_start + TIMINGS["commit_secs"]
    reveal_end = commit_end + TIMINGS["reveal_secs"]
    commits, reveals = [], []
    for i, (name, stake, answer, conf, revealed) in enumerate(entries):
        agent = account(name)
        evidence = json.dumps({"version": 1, "question_id": qid, "round": rnd, "agent": agent, "answer": answer})
        evidence_hash = sha256_hex(evidence)
        salt = sha256_hex(f"salt-{qid}-{rnd}-{name}")[:32]
        commits.append({
            "account_id": agent,
            "hash": commit_hash(qid, rnd, agent, answer, conf, evidence_hash, salt),
            "stake": str(stake),
            "committed_at": ns(commit_start + 20 + 15 * i),
        })
        if revealed:
            rep = rep_bps(*AGENTS[name][1:3])
            reveals.append({
                "account_id": agent,
                "answer": answer,
                "confidence": conf,
                "evidence_hash": evidence_hash,
                "evidence_uri": f"https://example.com/evidence/q{qid}/r{rnd}/{name}.json",
                "rep_bps": rep,
                "weight": str(weight(stake, rep, conf)),
                "revealed_at": ns(commit_end + 10 + 12 * i),
            })
    return {
        "round": rnd,
        "min_stake": str(min_stake),
        "commit_start": ns(commit_start),
        "commit_end": ns(commit_end),
        "reveal_end": ns(reveal_end),
        "commits": commits,
        "reveals": reveals,
        "tally": None,
    }


def tally(round_view, tallied_at):
    weights = {"YES": 0, "NO": 0, "INVALID": 0}
    for r in round_view["reveals"]:
        weights[r["answer"]] += int(r["weight"])
    total, top = sum(weights.values()), max(weights.values())
    leaders = [a for a, w in weights.items() if w == top]
    winner = leaders[0] if total and len(leaders) == 1 else None
    share = top * 10_000 // total if total else 0
    avg_conf = (
        sum(int(r["weight"]) * r["confidence"] for r in round_view["reveals"] if r["answer"] == winner) * 100 // top
        if winner else 0
    )
    revealed = len(round_view["reveals"])
    confident = winner is not None and share >= AUTO_SHARE_BPS and avg_conf >= AUTO_CONF_BPS and revealed >= MIN_AGENTS
    round_view["tally"] = {
        "weights": {a: str(w) for a, w in weights.items()},
        "winner": winner,
        "share_bps": share,
        "avg_conf_bps": avg_conf,
        "revealed": revealed,
        "confident": confident,
        "tallied_at": ns(tallied_at),
    }
    return round_view["tally"]


def settle(fee: int, rounds, final_answer: str):
    """Payouts for every commit in every round, against the final answer (interface.md section 5)."""
    protocol_fee = fee * PROTOCOL_FEE_BPS // 10_000
    rows, scores, total_slash = [], {}, 0
    for rv in rounds:
        revealed = {r["account_id"]: r for r in rv["reveals"]}
        for c in rv["commits"]:
            stake, r = int(c["stake"]), revealed.get(c["account_id"])
            key = (c["account_id"], rv["round"])
            if r is None:
                rows.append([key, stake, -stake, "no_reveal"])
                total_slash += stake
            elif r["answer"] == final_answer:
                scores[key] = stake * r["rep_bps"] * (10_000 - (100 - r["confidence"]) ** 2)
                rows.append([key, stake, 0, "correct"])
            else:
                slash = stake * r["confidence"] // 100
                rows.append([key, stake, -slash, "wrong"])
                total_slash += slash
    assert scores, "no-winner case (refund) is not used in the mock"
    pot = fee - protocol_fee + total_slash
    score_sum = sum(scores.values())
    for row in rows:
        if row[3] == "correct":
            row[2] = pot * scores[row[0]] // score_sum
    rewards = sum(row[2] for row in rows if row[3] == "correct")
    dust = pot - rewards
    assert 0 <= dust < len(scores), "dust is only rounding"
    assert fee + total_slash == protocol_fee + rewards + dust, "money must be conserved"
    payouts = [
        {"account_id": key[0], "round": key[1], "stake": str(stake), "delta": str(delta), "reason": reason}
        for key, stake, delta, reason in rows
    ]
    return payouts, protocol_fee, dust


def phase(q, now=NOW):
    status = q["status"]
    if status in ("Finalized", "Refunded"):
        return status
    if status == "Escalated":
        return "Dao"
    if status == "Provisional":
        return "Challenge" if now * 10**9 < int(q["challenge_end"]) else "AwaitingFinalize"
    rv = q["rounds"][-1]
    for name, end in (("Scheduled", "commit_start"), ("Commit", "commit_end"), ("Reveal", "reveal_end")):
        if now * 10**9 < int(rv[end]):
            return name
    return "AwaitingTally"


def question(qid, text, category, template, params, fee, resolve_after, created_at, rounds, **extra):
    q = {
        "id": qid, "asker": ASKER, "text": text, "category": category, "template": template,
        "params": json.dumps(params, separators=(",", ":")), "fee": str(fee),
        "created_at": ns(created_at), "resolve_after": ns(resolve_after), "timings": TIMINGS,
        "status": "Open", "phase": None, "round": len(rounds), "rounds": rounds,
        "challenge_end": None, "challenger": None, "outcome": None, "payouts": [],
        "protocol_fee": None, "dust": None, "finalized_at": None, "callback": None,
    }
    q.update(extra)
    q["phase"] = phase(q)
    return q


